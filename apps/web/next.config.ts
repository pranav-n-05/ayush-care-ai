import type { NextConfig } from "next";

// The browser talks only to this origin; /api/v1 is proxied to the FastAPI service so session
// cookies stay first-party (SameSite=Lax) and the API is never exposed cross-origin.
// Rewrites are resolved at BUILD time: set API_INTERNAL_URL when running `next build`.
const apiUrl = process.env.API_INTERNAL_URL ?? "http://localhost:8000";

const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "no-referrer" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

const config: NextConfig = {
  output: "standalone",
  poweredByHeader: false,
  async rewrites() {
    return [{ source: "/api/v1/:path*", destination: `${apiUrl}/api/v1/:path*` }];
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default config;
